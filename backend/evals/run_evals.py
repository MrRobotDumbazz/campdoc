#!/usr/bin/env python
"""Eval harness (PRD §9) — heuristic-mode (LLM pending).

Deterministic offline run over the shared datasets (data/datasets, seed 42):
- Diagnosis accuracy: top-1 / top-3 against ground-truth manifest modes via an
  explicit cause->mode table mirroring agent/heuristics.py rule causes.
- Groundedness: verifier pass (claims_grounded / claims_total, rule-based).
- Fix success: the top finding's structural changes[] replayed in the
  simulator (mock client by default; SIMULATOR_BASE_URL switches to the real
  simulator seam). Fix verified iff the simulator says verified=True for at
  least one proposed change (per-mode target metric, see MODE_TARGET_METRIC).
- False positives: healthy control must yield the "no major issue" verdict.
- Efficiency: median wall time of a full investigation.

No network calls except an optionally configured local simulator.
Output: markdown to stdout AND backend/evals/results.md.

Run: backend/.venv/bin/python backend/evals/run_evals.py
"""
from __future__ import annotations

import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from backend.config import Settings, get_settings  # noqa: E402
from backend.agent.runner import InvestigationRunner  # noqa: E402
from backend.tools import ToolRegistry, make_simulation_client  # noqa: E402
from backend.tools.loader import DatasetRepository  # noqa: E402

SEED = 42
QUESTION = "Why is this campaign underdelivering versus plan?"
RESULTS_PATH = Path(__file__).resolve().parent / "results.md"

# Explicit cause -> ground-truth mode table. Prefixes mirror the cause strings
# generated by backend/agent/heuristics.py for PRD §8 failure modes 1-7
# (and the healthy verdict). Eval mapping is versioned here, not guessed.
CAUSE_MODE_TABLE: list[tuple[str, int]] = [
    ("bid is below the market", 1),          # "Bid is below the market: ..."
    ("targeting is too narrow", 2),          # "Targeting is too narrow: ..."
    ("frequency cap is too strict", 3),      # "Frequency cap is too strict: ..."
    ("dayparting is too restrictive", 4),    # "Dayparting is too restrictive: ..."
    ("aggressive pacing (asap)", 5),         # "Aggressive pacing (ASAP) exhausts ..."
    ("floor price conflicts", 6),            # "Floor price conflicts: ..."
    ("spend concentrates on low-quality", 7),  # "Spend concentrates on low-quality ..."
    ("no major issue", 0),                   # healthy-control verdict
]

# Fix-verification target per mode: the metric the seeded fix is expected to
# move. Overspend (5) -> spend down; supply-path junk (7) -> spend off cheap
# sellers; everything else -> impressions up. (Direction handling belongs to
# the simulator: the mock treats spend/ecpm as lower-is-better.)
MODE_TARGET_METRIC: dict[int, str] = {5: "spend", 7: "spend"}

HEALTHY_MODES = {0, 8}


def cause_to_mode(cause: str) -> int | None:
    low = cause.lower()
    for prefix, mode in CAUSE_MODE_TABLE:
        if low.startswith(prefix):
            return mode
    return None


def run_eval(settings: Settings) -> str:
    repo = DatasetRepository(settings.data_dir)
    sim = make_simulation_client(repo, settings)
    rows: list[dict] = []
    for meta in repo.list_campaigns():
        cid = meta["campaign_id"]
        true_mode = repo.get(cid).ground_truth_mode
        registry = ToolRegistry(repo, settings)
        runner = InvestigationRunner(settings, registry, lambda *a: None)
        t0 = time.perf_counter()
        findings, extra = runner.run(cid, QUESTION)
        elapsed_ms = (time.perf_counter() - t0) * 1000
        verifier = extra["verifier"]

        predicted = [cause_to_mode(f.cause) for f in findings]
        top1 = predicted[0] if predicted else None
        top3 = predicted[:3]
        top1_ok = top1 == true_mode
        top3_ok = true_mode in top3

        # Fix success: replay each structural change of the TOP finding.
        fix_verified = None
        if true_mode not in HEALTHY_MODES and findings:
            target = MODE_TARGET_METRIC.get(true_mode, "impressions")
            fix_verified = False
            for change in findings[0].changes:
                if not change:
                    continue
                out = sim.run_simulation(cid, SEED, change, None, target)
                if out.get("verified"):
                    fix_verified = True
                    break

        rows.append({
            "campaign": cid, "mode": true_mode, "top1_ok": top1_ok, "top3_ok": top3_ok,
            "claims_grounded": verifier.claims_grounded, "claims_total": verifier.claims_total,
            "fix_verified": fix_verified, "elapsed_ms": elapsed_ms,
        })

    problem = [r for r in rows if r["mode"] not in HEALTHY_MODES]
    healthy = [r for r in rows if r["mode"] in HEALTHY_MODES]
    top1 = sum(r["top1_ok"] for r in problem) / max(len(problem), 1)
    top3 = sum(r["top3_ok"] for r in problem) / max(len(problem), 1)
    claims_t = sum(r["claims_total"] for r in rows)
    claims_g = sum(r["claims_grounded"] for r in rows)
    groundedness = claims_g / claims_t if claims_t else 1.0
    fixes = [r for r in problem if r["fix_verified"] is not None]
    fix_rate = sum(1 for r in fixes if r["fix_verified"]) / max(len(fixes), 1)
    fp = sum(1 for r in healthy if not r["top1_ok"])
    med_ms = statistics.median(r["elapsed_ms"] for r in rows)

    def pct(x: float) -> str:
        return f"{x * 100:.1f}%"

    mode_note = f"heuristic-mode (LLM pending), simulator: {sim.name}"
    if settings.simulator_base_url:
        mode_note += f" @ {settings.simulator_base_url}"

    lines = [
        "# Campaign Doctor — eval results (PRD §9)",
        "",
        f"Run configuration: seed {SEED}, datasets: "
        f"{'mock' if repo.using_mock_data() else 'data-dir'} "
        f"({settings.data_dir}), verifier: rule-based, **{mode_note}**.",
        "",
        "| metric | result | target |",
        "|---|---|---|",
        f"| Diagnosis top-1 | {pct(top1)} | ≥ 80% |",
        f"| Diagnosis top-3 | {pct(top3)} | ≥ 90% |",
        f"| Groundedness (verifier) | {pct(groundedness)} ({claims_g}/{claims_t}) | ≥ 95% |",
        f"| Fix success (simulator verified) | {pct(fix_rate)} | ≥ 75% |",
        f"| False positives on healthy control | {fp} | 0 |",
        f"| Median diagnosis time | {med_ms:.0f} ms | < 60 s |",
        "",
        "Per-campaign detail:",
        "",
        "| campaign | mode | top1 | top3 | groundedness | fix verified | time |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        g = f"{r['claims_grounded']}/{r['claims_total']}"
        fix = "—" if r["fix_verified"] is None else ("yes" if r["fix_verified"] else "no")
        lines.append(
            f"| {r['campaign']} | {r['mode']} | {'✅' if r['top1_ok'] else '❌'} "
            f"| {'✅' if r['top3_ok'] else '❌'} | {g} | {fix} | {r['elapsed_ms']:.0f} ms |")
    return "\n".join(lines) + "\n"


def main() -> None:
    report = run_eval(get_settings())
    sys.stdout.write(report)
    RESULTS_PATH.write_text(report, encoding="utf-8")
    sys.stdout.write(f"\n(written to {RESULTS_PATH})\n")


if __name__ == "__main__":
    main()
